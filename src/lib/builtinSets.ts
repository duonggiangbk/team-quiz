type Pair = [prompt: string, answer: string];

function build(slug: string, category: string, title: string, description: string, pairs: Pair[]): QuestionSet {
  const id = `builtin-${slug}`;
  return {
    id,
    title,
    description,
    category,
    updatedAt: 0,
    questions: pairs.map(([prompt, answer], i) => ({ id: `${id}-${i}`, prompt, answer, points: i % 3 === 2 ? 20 : 10 })),
  };
}

